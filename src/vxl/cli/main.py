"""Argument parsing and lazy dispatch for the unified ``vxl`` command."""

import argparse
import sys
from collections.abc import Sequence
from importlib import import_module
from ipaddress import IPv4Address
from pathlib import Path
from types import ModuleType
from typing import TextIO
from uuid import UUID

from .check import run_check
from .devices.shell import run as run_devices
from .node import serve as serve_node
from .station import import_catalog, initialize, initialize_legacy

_DEFAULT_HOST = str(IPv4Address(0))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="vxl", description="Voxel microscope control")
    commands = parser.add_subparsers(dest="command", metavar="<command>")

    init = commands.add_parser("init", help="create the station's station.yaml")
    init.add_argument("--name", required=True, help="human-readable station name")
    init.add_argument("--id", type=UUID, dest="station_id", help="stable station UUID (generated by default)")

    node = commands.add_parser("node", help="run a remote device node")
    node.add_argument("node_id", help="node identifier from the instrument config")
    node.add_argument("--address", "-a", required=True, help="ZMQ bind address")
    node.add_argument("--debug", action="store_true", help="enable debug logging")

    devices = commands.add_parser("devices", help="open devices from a config file and try them in a shell")
    devices.add_argument("config", type=Path, help="YAML with devices, such as an instrument file")
    devices.add_argument("devices", nargs="*", help="devices to open at start; the first becomes active")
    devices.add_argument("--log", type=Path, help="append a transcript to this file")

    serve = commands.add_parser("web-legacy", help="launch the legacy web application")
    serve.add_argument("--host", default=_DEFAULT_HOST, help="bind address (default: all interfaces)")
    serve.add_argument("--port", type=int, default=8000, help="web server port")
    serve.add_argument("--debug", action="store_true", help="enable debug logging")

    qt = commands.add_parser("qt", help="launch the legacy Qt application")
    qt.add_argument("config", nargs="?", type=Path, help="instrument configuration path")
    qt.add_argument("-v", "--verbose", action="store_true", help="enable verbose logging")

    check = commands.add_parser("check-legacy", help="statically validate legacy instrument configs")
    check.add_argument("paths", nargs="*", type=Path, help="config files, instrument directories, or collections")
    check.add_argument("--json", action="store_true", dest="as_json", help="emit machine-readable JSON")

    init_legacy = commands.add_parser("init-legacy", help="create the legacy station's station.yaml")
    init_legacy.add_argument("--name", required=True, help="human-readable station name")
    init_legacy.add_argument("--id", type=UUID, dest="station_id", help="stable station UUID (generated by default)")

    commands.add_parser(
        "import-catalog",
        help="import the legacy file catalog into the legacy records.sqlite3 without modifying its files",
    )
    return parser


def _load_optional(module: str, extra: str, stderr: TextIO) -> ModuleType | None:
    try:
        return import_module(module)
    except ModuleNotFoundError as error:
        missing = error.name or "an optional dependency"
        if missing == "vxl" or missing.startswith("vxl."):
            raise
        stderr.write(
            f"Unable to load optional {extra} support because `{missing}` is missing. "
            f"Install it with `uv sync --extra {extra}` or `pip install 'vxl[{extra}]'`.\n"
        )
        return None


def run(
    argv: Sequence[str] | None = None,
    *,
    stdout: TextIO | None = None,
    stderr: TextIO | None = None,
) -> int:
    """Dispatch one CLI invocation and return its process exit code. With no command, print the help."""
    parser = build_parser()
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    output = sys.stdout if stdout is None else stdout
    errors = sys.stderr if stderr is None else stderr

    match args.command:
        case None:
            parser.print_help(output)
            return 0
        case "init":
            return initialize(args.name, station_id=args.station_id, output=output, errors=errors)
        case "node":
            serve_node(args.node_id, args.address, debug=args.debug)
            return 0
        case "devices":
            return run_devices(args.config, args.devices, log=args.log)
        case "web-legacy":
            web_app = _load_optional("vxl.web.app", "web", errors)
            if web_app is None:
                return 2
            web_app.serve(host=args.host, port=args.port, debug=args.debug)
            return 0
        case "qt":
            qt_app = _load_optional("vxl.qt.app", "qt", errors)
            if qt_app is None:
                return 2
            return qt_app.launch(args.config, verbose=args.verbose)
        case "check-legacy":
            return run_check(args.paths, as_json=args.as_json, output=output)
        case "init-legacy":
            return initialize_legacy(args.name, station_id=args.station_id, output=output, errors=errors)
        case "import-catalog":
            return import_catalog(output=output, errors=errors)
        case _:
            raise AssertionError(f"Unhandled command: {args.command}")


def main() -> None:
    raise SystemExit(run())
