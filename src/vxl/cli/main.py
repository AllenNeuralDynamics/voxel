"""Argument parsing and lazy dispatch for the unified ``vxl`` command."""

import argparse
import sys
from collections.abc import Sequence
from importlib import import_module
from ipaddress import IPv4Address
from pathlib import Path
from types import ModuleType
from typing import TextIO
from uuid import UUID

from .check import run_check
from .devices.shell import run as run_devices
from .node import serve as serve_node
from .station import import_catalog, initialize, initialize_legacy

_DEFAULT_HOST = str(IPv4Address(0))


def build_parser() -> argparse.ArgumentParser:
    """The ``vxl`` parser: a product, then an action. Each parser stores itself as ``parser`` so a bare product can
    print its own help."""
    parser = argparse.ArgumentParser(prog="vxl", description="Voxel microscope control")
    parser.set_defaults(parser=parser)
    products = parser.add_subparsers(dest="product", metavar="<product>")

    station = _group(products, "station", "set up and run a station")
    init = station.add_parser("init", help="create the station's station.yaml")
    _identity(init)

    node = _group(products, "node", "host devices for a station on this machine")
    start = node.add_parser("start", help="start a device node")
    start.add_argument("node_id", help="node identifier from the instrument config")
    start.add_argument("--address", "-a", required=True, help="ZMQ bind address")
    start.add_argument("--debug", action="store_true", help="enable debug logging")

    devices = _group(products, "devices", "try devices without an instrument")
    shell = devices.add_parser("shell", help="open devices from a rig file and try them in a shell")
    shell.add_argument("config", type=Path, help="rig file, such as an instrument's rig.yaml")
    shell.add_argument("devices", nargs="*", help="devices to open at start; the first becomes active")
    shell.add_argument("--log", type=Path, help="append a transcript to this file")

    legacy = _group(products, "legacy", "the legacy applications, until they are removed")
    web = legacy.add_parser("web", help="launch the legacy web application")
    web.add_argument("--host", default=_DEFAULT_HOST, help="bind address (default: all interfaces)")
    web.add_argument("--port", type=int, default=8000, help="web server port")
    web.add_argument("--debug", action="store_true", help="enable debug logging")
    qt = legacy.add_parser("qt", help="launch the legacy Qt application")
    qt.add_argument("config", nargs="?", type=Path, help="instrument configuration path")
    qt.add_argument("-v", "--verbose", action="store_true", help="enable verbose logging")
    check = legacy.add_parser("check", help="statically validate legacy instrument configs")
    check.add_argument("paths", nargs="*", type=Path, help="config files, instrument directories, or collections")
    check.add_argument("--json", action="store_true", dest="as_json", help="emit machine-readable JSON")
    _identity(legacy.add_parser("init", help="create the legacy station's station.yaml"))
    legacy.add_parser("import-catalog", help="import the legacy file catalog into the legacy records")
    return parser


def _group(
    products: "argparse._SubParsersAction[argparse.ArgumentParser]", name: str, summary: str
) -> "argparse._SubParsersAction[argparse.ArgumentParser]":
    group = products.add_parser(name, help=summary, description=summary)
    group.set_defaults(parser=group)
    return group.add_subparsers(dest="action", metavar="<action>")


def _identity(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--name", required=True, help="human-readable station name")
    parser.add_argument("--id", type=UUID, dest="station_id", help="stable station UUID (generated by default)")


def _load_optional(module: str, extra: str, stderr: TextIO) -> ModuleType | None:
    try:
        return import_module(module)
    except ModuleNotFoundError as error:
        missing = error.name or "an optional dependency"
        if missing == "vxl" or missing.startswith("vxl."):
            raise
        stderr.write(
            f"Unable to load optional {extra} support because `{missing}` is missing. "
            f"Install it with `uv sync --extra {extra}` or `pip install 'vxl[{extra}]'`.\n"
        )
        return None


def run(
    argv: Sequence[str] | None = None,
    *,
    stdout: TextIO | None = None,
    stderr: TextIO | None = None,
) -> int:
    """Dispatch one CLI invocation and return its process exit code. A bare ``vxl`` or product prints its help."""
    args = build_parser().parse_args(sys.argv[1:] if argv is None else argv)
    output = sys.stdout if stdout is None else stdout
    errors = sys.stderr if stderr is None else stderr

    match args.product, getattr(args, "action", None):
        case (None, _) | (_, None):
            args.parser.print_help(output)
            return 0
        case "station", "init":
            return initialize(args.name, station_id=args.station_id, output=output, errors=errors)
        case "node", "start":
            serve_node(args.node_id, args.address, debug=args.debug)
            return 0
        case "devices", "shell":
            return run_devices(args.config, args.devices, log=args.log)
        case "legacy", "web":
            web_app = _load_optional("vxl.web.app", "web", errors)
            if web_app is None:
                return 2
            web_app.serve(host=args.host, port=args.port, debug=args.debug)
            return 0
        case "legacy", "qt":
            qt_app = _load_optional("vxl.qt.app", "qt", errors)
            if qt_app is None:
                return 2
            return qt_app.launch(args.config, verbose=args.verbose)
        case "legacy", "check":
            return run_check(args.paths, as_json=args.as_json, output=output)
        case "legacy", "init":
            return initialize_legacy(args.name, station_id=args.station_id, output=output, errors=errors)
        case "legacy", "import-catalog":
            return import_catalog(output=output, errors=errors)
        case product, action:
            raise AssertionError(f"Unhandled command: {product} {action}")


def main() -> None:
    raise SystemExit(run())
